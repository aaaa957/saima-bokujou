'use strict';
// The full numerical matrix uses this archived source. A later lifecycle-only
// entry fix and a telemetry-only predicate repair are accepted only if their
// exact inverse patches restore the entire
// normalized snapshot byte for byte. No physics region is excluded from hash.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),zlib=require('node:zlib'),crypto=require('node:crypto');
const ROOT=path.resolve(__dirname,'../..');
const NUMERIC_HASH='3b837b46bf03ed86a19fdbe0ff83a03bb4fd2211ff9a4692b2f1a78e12f221ff';
const archivePath=path.join(ROOT,'docs/system-numeric-source-3b837b-v9.js.gz');
const normalize=s=>s.replace(/\r\n/g,'\n');
const hash=s=>crypto.createHash('sha256').update(normalize(s)).digest('hex');
function source(){const s=zlib.gunzipSync(fs.readFileSync(archivePath)).toString('utf8');assert.equal(hash(s),NUMERIC_HASH,'Numeric snapshot archive changed');return s;}
function verify(){
  const archived=normalize(source()),current=normalize(fs.readFileSync(path.join(ROOT,'sim.js'),'utf8')),currentHash=hash(current);
  if(currentHash===NUMERIC_HASH)return {numericEngineHash:NUMERIC_HASH,currentEngineHash:currentHash,mode:'identical-source',entireSourceExact:true,exactInversePatchMatchesSnapshot:true,lifecycleOnly:false};
  const begin=current.indexOf('  function raceOptionsForRoster(h, rng, roster, weekNum) {\n');
  const end=current.indexOf('  /* ---------------- 下注玩法',begin);
  assert(begin>=0&&end>begin,'Cannot isolate the legacy roster entry function');
  let region=current.slice(begin,end);
  const additions=[
    '    horsePhysiology(h);\n',
    '        physiology: { ...h.physiology },\n',
  ];
  for(const line of additions){assert.equal(region.split(line).length-1,1,'Expected exactly one lifecycle addition in raceOptionsForRoster');region=region.replace(line,'');}
  const reversed=current.slice(0,begin)+region+current.slice(end);
  const oldDiagnostic=[
    '          race.traffic.minFollowingSlack=race.traffic.minFollowingSlack==null?slack:Math.min(race.traffic.minFollowingSlack,slack);',
    '          race.traffic.minResponseSlack=race.traffic.minResponseSlack==null?response:Math.min(race.traffic.minResponseSlack,response);',
  ].join('\n');
  const newDiagnostic=[
    '          if(axisOverlap(fm.t-rm.t,fm.t-rm.t,clear.lateral)) {',
    '            race.traffic.minFollowingSlack=race.traffic.minFollowingSlack==null?slack:Math.min(race.traffic.minFollowingSlack,slack);',
    '            race.traffic.minResponseSlack=race.traffic.minResponseSlack==null?response:Math.min(race.traffic.minResponseSlack,response);',
    '          }',
  ].join('\n');
  const diagnosticChanged=reversed.includes(newDiagnostic);
  let restored=reversed;
  if(diagnosticChanged){assert.equal(restored.split(newDiagnostic).length-1,1,'Expected one telemetry predicate repair');assert.equal(restored.split(oldDiagnostic).length-1,0);restored=restored.replace(newDiagnostic,oldDiagnostic);}
  assert.equal(restored,archived,'Changes beyond the reviewed entry lines and telemetry predicate require new numerical validation');
  assert.equal(hash(restored),NUMERIC_HASH);
  return {numericEngineHash:NUMERIC_HASH,currentEngineHash:currentHash,mode:diagnosticChanged?'exact-entry-and-telemetry-inverse-patches':'exact-two-line-lifecycle-reversal',entireSourceExact:true,exactInversePatchMatchesSnapshot:true,lifecycleOnly:!diagnosticChanged,lifecycleEntryChanges:true,diagnosticPredicateOnly:diagnosticChanged,telemetryQueryOrderPreserved:diagnosticChanged,physicsAndSolverSourceExact:true,
    changedFunction:'raceOptionsForRoster',addedLines:additions.map(s=>s.trim()),
    numericalEntry:'Formal fields are generated by frozen-v8 fieldFor and enter createRace directly; they do not call raceOptionsForRoster.',
    telemetryRepair:diagnosticChanged?{old:oldDiagnostic.trim(),current:newDiagnostic.trim(),scope:'Only gate the two final race.traffic min assignments. Original outer condition, followingSlack calls, their order and persistent witness cache writes remain unchanged; movement and solver source are unchanged.'}:null,
    limitation:'Full matrices ran on the archived numeric hash. Entry migration/copying and telemetry correction are separately audited; raw data is never relabeled with the production hash.'};
}
module.exports={NUMERIC_HASH,archivePath,source,verify};
